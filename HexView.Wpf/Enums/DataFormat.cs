/// <summary>
/// Enumerates the data column formatting options.
/// </summary>
public enum DataFormat
{
    /// <summary>
    /// Formats the data column as decimal integer.
    /// </summary>
    Decimal,

    /// <summary>
    /// Formats the data column as hexadecimal integer.
    /// </summary>
    Hexadecimal,
}
