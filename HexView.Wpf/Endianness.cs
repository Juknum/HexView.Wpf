namespace HexView.Wpf
{
    /// <summary>
    /// Enumerates the endianness options.
    /// </summary>
    public enum Endianness
    {
        /// <summary>
        /// Big-endian format (most significant byte first).
        /// </summary>
        BigEndian,

        /// <summary>
        /// Little-endian format (least significant byte first).
        /// </summary>
        LittleEndian,
    }
}
